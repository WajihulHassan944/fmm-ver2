function App({ Component, ...rest }) {
  const { store, props } = wrapper.useWrappedStore(rest); // Wrapped store for SSR

  const router = useRouter();
  const loadMarketingScripts = !router.pathname.startsWith("/administration");
  const loadAds = loadMarketingScripts &&
    !["/auth", "/login", "/CreateAccount", "/AffiliateCreateAccount", "/affiliate-create-account", "/checkout"].includes(router.pathname);

  return (
    <>
      <SeoHead />
      {loadMarketingScripts && (
        <>
          <Script
            async
            src="https://www.googletagmanager.com/gtag/js?id=AW-16787825610"
            strategy="lazyOnload"
          />

          <Script id="google-analytics" strategy="lazyOnload">
            {`
              window.dataLayer = window.dataLayer || [];
              function gtag(){dataLayer.push(arguments);}
              gtag('js', new Date());
              gtag('config', 'AW-16787825610');
            `}
          </Script>
        </>
      )}

      {loadAds && (
        <Script
          async
          src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-7572941850845854"
          crossOrigin="anonymous"
          strategy="lazyOnload"
        />
      )}

      <Provider store={store}>
        <AppContent>
          <Component {...props.pageProps} />
        </AppContent>
      </Provider>
    </>
  );
}

function AppContent({ children }) {
  const router = useRouter();
  const dispatch = useDispatch();
  const [isExactMobile, setIsExactMobile] = useState(false);
  const isPlaying = useSelector((state) => state.music.isPlaying);
  const seekPosition = useSelector((state) => state.music.seekPosition);
  const howlerRef = useRef(null);
  const { isAdminAuthenticated } = useSelector((state) => state.adminAuth);

  const isAdministrationRoute = router.pathname.startsWith("/administration");
  const isAdminLoginRoute = router.pathname === "/administration/login";
  const isHomeExperienceRoute = router.pathname === "/" || router.pathname === "/home";
  const isStandaloneDemoRoute = ["/free-demo", "/mock-game", "/playforfree"].includes(router.pathname);
  // Keep the global site header hidden for admin and the standalone demo app.
  // The homepage still needs the normal desktop/laptop navbar, while CSS hides
  // it on phone so the standalone mobile app topbar remains clean.
  // The new homepage (pages/welcome.js, reused by pages/index.js) brings its own
  // nav and footer, so the legacy site chrome must not be layered on top of it.
  const hideLayout = isAdministrationRoute || isStandaloneDemoRoute
    || router.pathname.startsWith("/score")
    || router.pathname === "/" || router.pathname === "/welcome";
  const hideFooterChrome = isAdministrationRoute || isHomeExperienceRoute || isStandaloneDemoRoute || router.pathname.startsWith("/score") || IMMERSIVE_ROUTES.has(router.pathname);
  const showAdminChrome = isAdministrationRoute && !isAdminLoginRoute;
  const useRouteExperienceFrame = shouldUseRouteExperienceFrame(
    router.pathname,
  );
  const exactMobileTab = MOBILE_APP_ROUTE_TABS[router.pathname] || null;
  // Product routes are one responsive app now: use the approved app shell on
  // both phone and desktop instead of falling back to legacy page bodies.
  const forcePrototypeExperience = Boolean(exactMobileTab);
  // Render the phone shell in the initial HTML for mapped routes. CSS keeps it
  // hidden on desktop, while mobile no longer waits for a post-hydration chunk
  // and media-query state update before the app appears.
  const renderPrototypeExperience = Boolean(exactMobileTab);
  const renderLegacyExperience = !forcePrototypeExperience && (!exactMobileTab || !isExactMobile);
  const mainClassName = isAdministrationRoute
    ? isAdminLoginRoute
      ? "admin-login-main"
      : "admin-experience-main"
    : `site-experience-main${isHomeExperienceRoute ? " is-home-experience-main" : ""}${isStandaloneDemoRoute ? " is-standalone-demo-main" : ""}`;

  useEffect(() => {
    const media = window.matchMedia(EXACT_MOBILE_QUERY);
    const sync = () => setIsExactMobile(media.matches);
    sync();
    media.addEventListener?.("change", sync);
    return () => media.removeEventListener?.("change", sync);
  }, []);

  useEffect(() => {
    if (!router.isReady) return undefined;

    let cleanupScroll = () => {};
    const timer = window.setTimeout(() => {
      const header = document.querySelector(".header");
      if (!header) return;

      const handleScroll = () => {
        if (window.scrollY > 0) {
          header.style.backgroundColor = "black";
          return;
        }

        const darkRoutes = [
          "/community-forum",
          "/Sponsors",
          "/guides",
          "/our-fighters",
          "/faqs",
          "/about",
          "/past-fights-records",
          "/fights-rewards",
          "/sponsor-dashboard",
          "/global-leaderboard",
          "/testimonials",
          "/spin-wheel",
          "/calendar-of-fights",
          "/AffiliateDashboard",
          "/AffiliateProfile",
          "/AffiliateAccountSettings",
          "/past-promotions",
          "/past-fights",
          "/fight",
          "/referral-leaderboard",
          "/HowItWorks",
          "/affiliate-league",
          "/fantasy-tips",
          "/FantasyLeagues",
          "/invite",
          "/fighter-performance-tracker",
          "/leaderboard",
          "/mock-game",
          "/free-demo",
          "/UserDashboard",
          "/YourFights",
          "/trashed-fights",
          "/profile",
          "/account-settings",
          "/checkout",
          "/my-fantasy-team",
          "/pro-wrestling",
        ];

        const redRoutes = ["/fights-news"];
        const baseRoute = "/" + router.asPath.split("/")[1];

        if (darkRoutes.includes(baseRoute)) {
          header.style.backgroundColor = "#000000";
        } else if (redRoutes.includes(baseRoute)) {
          header.style.backgroundColor = "#dc1606";
        } else {
          header.style.backgroundColor = "rgba(0, 0, 0, 0.6)";
        }
      };

      handleScroll();
      window.addEventListener("scroll", handleScroll, { passive: true });
      cleanupScroll = () => window.removeEventListener("scroll", handleScroll);
    }, 100);

    return () => {
      window.clearTimeout(timer);
      cleanupScroll();
    };
  }, [router.pathname, router.asPath, router.isReady]);

  useEffect(() => {
    if (typeof window === "undefined") return undefined;

    const shouldFetchProfilesImmediately = routeMatchesPrefix(
      router.pathname,
      AUTH_PROFILE_CRITICAL_PREFIXES,
    );
    const cleanupFns = [];
    const runProfileFetch = (callback) => {
      if (shouldFetchProfilesImmediately) {
        callback();
        return undefined;
      }
      return scheduleWhenIdle(callback, 1800);
    };

    // Owner "view as": a read-only preview token in sessionStorage stands in for
    // the account being viewed, so the whole app hydrates as that person. It is
    // never written to localStorage, so it cannot outlive the tab or displace a
    // real login — and the server refuses any non-GET made with it.
    let previewToken = '';
    let previewType = '';
    try {
      previewToken = sessionStorage.getItem('previewToken') || '';
      previewType = JSON.parse(sessionStorage.getItem('previewContext') || '{}')?.type || '';
    } catch (error) { /* ignore */ }

    const userToken = previewToken && previewType !== 'affiliate'
      ? previewToken
      : localStorage.getItem("authToken");
    if (userToken) {
      dispatch(setUser({ token: userToken }));
      const cleanup = runProfileFetch(() => dispatch(fetchUser(userToken)));
      if (cleanup) cleanupFns.push(cleanup);
    }

    const affiliateToken = previewToken && previewType === 'affiliate'
      ? previewToken
      : localStorage.getItem("affiliateAuthToken");
    if (affiliateToken) {
      dispatch(setAffiliateUser({ token: affiliateToken }));
      const cleanup = runProfileFetch(() => dispatch(fetchAffiliate(affiliateToken)));
      if (cleanup) cleanupFns.push(cleanup);
    }

    const adminToken = localStorage.getItem("adminAuthToken");
    if (adminToken) {
      dispatch(setAdminAuthenticated({ token: adminToken }));
    }

    return () => cleanupFns.forEach((cleanup) => cleanup?.());
  }, [dispatch, router.pathname]);

  useEffect(() => {
    if (isPlaying && howlerRef.current) {
      console.log("Seeking to position:", seekPosition);
      howlerRef.current.seek(seekPosition);
    }
  }, [isPlaying, seekPosition]);

  const getOrCreateDeviceId = () => {
    let deviceId =
      typeof window !== "undefined" && localStorage.getItem("deviceId");
    if (!deviceId) {
      deviceId =
        globalThis.crypto?.randomUUID?.() ||
        `${Date.now()}-${Math.random().toString(36).slice(2)}`;
      localStorage.setItem("deviceId", deviceId);
    }
    return deviceId;
  };

  useEffect(() => {
    const cleanupIdle = scheduleWhenIdle(() => {
      const deviceId = getOrCreateDeviceId();

      fetch(`${API_BASE_URL}/track-click`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ deviceId }),
        keepalive: true,
      }).catch((err) => console.error("Error tracking page view:", err));
    }, 4000);

    return () => cleanupIdle?.();
  }, []);

  const handleTogglePlayPause = () => {
    if (isPlaying) {
      const currentSeek = howlerRef.current?.seek() || 0;
      console.log("Stopping music. Current seek position:", currentSeek);
      dispatch(stopMusic(currentSeek));
    } else {
      console.log("Playing music from position:", seekPosition);
      dispatch(playMusic());
    }
  };

  return (
    <>
      <Head>
        {/* Legacy-only stylesheets: 570 KB that styles website pages the app
            never renders. Verified class-scoped (no body/html/:root/@font-face),
            so the app cannot depend on them. Originals kept in
            src/styles/_backup-legacy-css/ — to revert, move a file back and
            re-add its import above. */}
        {renderLegacyExperience && (
          <>
            <link rel="stylesheet" href="/legacy-css/featured-fight-stage-final.css" />
            <link rel="stylesheet" href="/legacy-css/pro-wrestling.css" />
            <link rel="stylesheet" href="/legacy-css/experience-theme.css" />
            <link rel="stylesheet" href="/legacy-css/affiliate-experience-final.css" />
            {/* Legacy halves of the four split sheets — 492 KB the app route no
                longer parses. Ordered as they were bundled, so the cascade
                between them is preserved. */}
            <link rel="stylesheet" href="/legacy-css/globals.css" />
            <link rel="stylesheet" href="/legacy-css/frontend-final.css" />
            <link rel="stylesheet" href="/legacy-css/new-theme.css" />
            <link rel="stylesheet" href="/legacy-css/client-feedback-final.css" />
          </>
        )}

        {/* Start the banner download in the document head rather than waiting for
            the placeholder to render. Both sizes are declared with the same media
            queries the <picture> uses, so the browser fetches exactly one. */}
        <link
          rel="preload"
          as="image"
          href="/images/mobile-home/final-v35/hero-banner-v2-mobile.jpg"
          media="(max-width: 767px)"
          fetchpriority="high"
        />
        <link
          rel="preload"
          as="image"
          href="/images/mobile-home/final-v35/hero-banner-v2.jpg"
          media="(min-width: 768px)"
          fetchpriority="high"
        />
      </Head>

      <style jsx global>{`
        /* Phone: the app owns the whole viewport, exactly as before. */
        .fmm-app-desktop-shell { width: 100%; }

        @media (min-width: 768px) {
          /* Desktop: stop stretching a phone layout across a monitor. The app
             sits in a fixed phone-width column on a branded backdrop, so every
             internal layout gets the width it was designed for. */
          .fmm-app-desktop-shell {
            min-height: 100vh;
            background:
              radial-gradient(900px 520px at 50% -8%, rgba(242,181,68,.10), transparent 62%),
              #05060a;
            display: flex;
            justify-content: center;
            align-items: flex-start;
            padding: 0;
          }
          .fmm-app-desktop-column {
            width: 100%;
            max-width: 460px;
            min-height: 100vh;
            background: #05060a;
            border-left: 1px solid rgba(255,255,255,.09);
            border-right: 1px solid rgba(255,255,255,.09);
            box-shadow: 0 0 70px rgba(0,0,0,.65);
            position: relative;
          }
          /* The feedback button is position:fixed, which is correct — it must
             stay pinned to the viewport while the app scrolls. Only its
             horizontal anchor is wrong on desktop: right:12 puts it against the
             monitor edge instead of the column. Pull it to the column's right
             edge (half the 460px column, less the 12px inset) and leave the
             vertical pinning alone. Deliberately scoped to this one element —
             a blanket [style*="fixed"] rule would silently change behaviour for
             any element that ever uses fixed positioning. */
          .fmm-feedback-fab { right: calc(50% - 218px) !important; }
        }
      `}</style>

      <div style={{ zIndex: "99999999999" }}>
        <ToastContainer />
      </div>

      {/* Never show the legacy site header while the app is rendering — it has
          its own topbar. This used to key off isExactMobile, so viewing the app
          at anything wider than the phone breakpoint (a laptop, a resized
          window) stacked the old site header above the app's real one. */}
      {!hideLayout && !renderPrototypeExperience && <Header />}
      {renderLegacyExperience && showAdminChrome && <AdminHeader />}
      {renderLegacyExperience && !hideFooterChrome && <ChatbaseWidget />}
      {renderPrototypeExperience && (
        <div className="fmm-app-desktop-shell">
          <div className="fmm-app-desktop-column">
            <FantasyMobileExperience initialTab={exactMobileTab} forceRender={forcePrototypeExperience} />
          </div>
        </div>
      )}

      {renderLegacyExperience && <main className={mainClassName}>
        {useRouteExperienceFrame ? (
          <RouteExperienceFrame pathname={router.pathname}>
            {children}
          </RouteExperienceFrame>
        ) : (
          children
        )}
      </main>}
      {renderLegacyExperience && !hideFooterChrome && <Footer />}
    </>
  );
}

